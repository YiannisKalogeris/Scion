r"""
Emit the LaTeX tables for Section 6 of the paper.

Numbers in a manuscript should be regenerated, not transcribed: a table typed by
hand is a table that silently disagrees with the code after the next change.
This writes one ``tab_*.tex`` per table into the manuscript directory, each a
complete ``\begin{table}...\end{table}`` with its own label, so the sections file
only has to ``\input`` them.

    python -m projects.configurational_mpm.paper_tables --out _incoming/myArticle

``--quick`` shortens every run; the numbers are then indicative and the tables
say so in their captions.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from scion.core.logging import quiet
from scion.discretization.mpm import (
    CPDIGrid, CartesianGrid, ExplicitMPMStepper, ParticleSet,
)
from scion.materials.hyperelastic_batched import NeoHookeanCompressible
from projects.configurational_mpm import ranking as R

__all__ = ["write_all"]

_PROVENANCE = ("%% generated by projects/configurational_mpm/paper_tables.py "
               "-- do not edit by hand\n")


def _fmt(x, digits=2):
    """LaTeX scientific notation, or a dash for a failed run."""
    if x is None or not np.isfinite(x):
        return "---"
    if x == 0.0:
        return "$0$"
    exp = int(np.floor(np.log10(abs(x))))
    mant = x / 10.0 ** exp
    return rf"${mant:.{digits}f}\times10^{{{exp}}}$"


def _table(body, caption, label, colspec, header):
    return (
        _PROVENANCE
        + "\\begin{table}[htbp]\n\\centering\n"
        + f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        + f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n"
        + header + "\n\\midrule\n" + body + "\n\\bottomrule\n"
        + "\\end{tabular}\n\\end{table}\n"
    )


