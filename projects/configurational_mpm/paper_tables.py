def write_all(out_dir, steps=300, quick=False):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    if quick:
        steps = 60
    tables = {
        "tab_pseudomomentum.tex": lambda: table_pseudomomentum(steps),
        "tab_angular.tex": lambda: table_angular(min(steps, 300)),
        "tab_diagnostics.tex": lambda: table_diagnostics(steps),
        "tab_regularity.tex": table_regularity,
        "tab_refinement.tex": lambda: table_refinement(0.02 if quick else 0.08),
        "tab_ranking.tex": lambda: table_ranking(steps),
    }
    for name, fn in tables.items():
        (out / name).write_text(fn())
        print(f"  wrote {out / name}")
    return sorted(tables)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="_incoming/myArticle")
    ap.add_argument("--steps", type=int, default=300)
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    print(f"writing tables to {a.out}")
    write_all(a.out, steps=a.steps, quick=a.quick)
