def table_pseudomomentum(steps):
    rows = []
    for v in R.variants():
        dP, dp, err = R.run_one(v, R.shear_wave, steps)
        rows.append(f"{v.label} & {_fmt(dp)} & {_fmt(dP)} \\\\"
                    if err is None else
                    f"{v.label} & \\multicolumn{{2}}{{c}}{{{err}}} \\\\")
    return _table(
        "\n".join(rows),
        "Drift of the discrete pseudomomentum \\eqref{eq:discrete-pseudomomentum} "
        "against that of the spatial linear momentum, over the same runs. "
        "Homogeneous body in a periodic cell, shear-wave initial field, "
        f"{steps} steps. Both scaled by $M v_{{\\mathrm{{rms}}}}$. Linear "
        "momentum is conserved to machine precision by every scheme; "
        "pseudomomentum is not conserved by any.",
        "tab:pseudomomentum", "lcc",
        "Variant & $\\|\\Delta \\sum m\\boldsymbol{v}\\|$ & "
        "$\\|\\Delta \\boldsymbol{\\mathcal{P}}_{h}\\|$ \\\\")


def table_angular(steps):
    from tests.mpm.test_noether_corollaries import drift, NullMaterial
    from scion.discretization.mpm import APIC, FLIP, MLSMPM, PIC

    mat = NeoHookeanCompressible.from_E_nu(R.E, R.NU)
    rows = []
    for name, tr in [("PIC", PIC()), ("FLIP $\\alpha=1$", FLIP(alpha=1.0)),
                     ("APIC", APIC()), ("MLS-MPM", MLSMPM())]:
        bulk, total = drift(tr, NullMaterial(), steps=steps)
        _, total_f = drift(tr, mat, steps=steps)
        rows.append(f"{name} & {_fmt(bulk)} & {_fmt(total)} & {_fmt(total_f)} \\\\")
    return _table(
        "\n".join(rows),
        "Angular momentum drift, free spinning body, no body force and no "
        "boundaries. ``Bulk'' is $\\sum_p m_p \\boldsymbol{x}_p\\times"
        "\\boldsymbol{v}_p$; ``total'' is the full momentum map "
        "\\eqref{eq:angular-momentum-map} including the affine contribution. "
        "The enlargement is where the conserved quantity lives.",
        "tab:angular", "lccc",
        "Transfer & Bulk only & Total (transfer) & Total (with stress) \\\\")


def table_diagnostics(steps):
    from tests.test_projects.test_diagnostic_comparison import energy_ordering

    rows = []
    for fname in ("shear wave", "vortex array", "multimode"):
        flow = R.BENCHMARKS[fname]
        got = [(v.label, *R.run_one_with_G(v, flow, steps)[:2])
               for v in R.variants()]
        got = [g for g in got if g[1] is not None]
        by_P = [g[0] for g in sorted(got, key=lambda t: t[1])]
        by_G = [g[0] for g in sorted(got, key=lambda t: t[2])]
        by_ke, _ = energy_ordering(flow, steps)
        rows.append(f"{fname} & {R.spearman(by_P, by_ke):+.2f} & "
                    f"{R.spearman(by_G, by_ke):+.2f} & "
                    f"{R.spearman(by_P, by_G):+.2f} \\\\")
    return _table(
        "\n".join(rows),
        "Spearman rank correlation of each diagnostic against kinetic-energy "
        "retention, an independent quality measure, and against each other. "
        f"Periodic cell, {steps} steps. The configurational-force ordering "
        "tracks quality; the pseudomomentum ordering does not, and the two "
        "orderings are not the same.",
        "tab:diagnostics", "lccc",
        "Benchmark & $\\rho(\\mathcal{P}_h,\\mathrm{KE})$ & "
        "$\\rho(\\mathcal{G}_i,\\mathrm{KE})$ & "
        "$\\rho(\\mathcal{P}_h,\\mathcal{G}_i)$ \\\\")


def table_regularity():
    from tests.mpm.test_second_gradient_regularity import peak_and_jump

    rows = [r"Piecewise multilinear & unbounded & --- & Dirac measure \\"]
    for kind, label in [("cubic", "B-spline, cubic"),
                        ("quadratic", "B-spline, quadratic"),
                        ("cpdi", "CPDI (multilinear)"),
                        ("gimp", "uGIMP")]:
        peak, jump = peak_and_jump(kind)
        char = ("continuous" if jump / peak < 1e-2
                else "bounded, discontinuous")
        rows.append(f"{label} & {_fmt(peak)} & {jump/peak:.2f} & {char} \\\\")
    return _table(
        "\n".join(rows),
        "Regularity of the second material gradient of the grid basis, "
        "$\\partial^{2}w/\\partial X^{2}$, profiled at a \\emph{fixed} node as a "
        "particle is swept past it. Summing over the stencil instead would "
        "report the quadratic B-spline as continuous.",
        "tab:regularity", "lccl",
        "Basis & Peak $|\\partial^{2}w|$ & Jump/peak & Character \\\\")


def table_refinement(t_end=0.08):
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    grids = [12, 16, 24, 32]
    picks = ["BSMPM cubic", "BSMPM quad", "uGIMP", "CPDI", "MPM (linear)"]
    vals = {}
    for lbl in picks:
        v = next(x for x in R.variants() if x.label == lbl)
        vals[lbl] = [_refine_one(v, t_end, n) for n in grids]

    rows = []
    for lbl in picks:
        cells = " & ".join(_fmt(x) for x in vals[lbl])
        good = [(n, x) for n, x in zip(grids, vals[lbl]) if x and x > 0]
        rate = (np.polyfit(np.log([1 / n for n, _ in good]),
                           np.log([x for _, x in good]), 1)[0]
                if len(good) >= 3 else float("nan"))
        rows.append(f"{lbl} & {cells} & {rate:.2f} \\\\")
    return _table(
        "\n".join(rows),
        "$\\|\\boldsymbol{\\mathcal{G}}_{i}\\|$ under grid refinement at "
        f"\\emph{{fixed physical time}} $T={t_end}$, shear-wave benchmark. "
        "Fixing the number of steps instead would compare different end times, "
        "since $\\Delta t \\propto h$. The rate is common to all variants; the "
        "constants differ and the spread narrows under refinement.",
        "tab:refinement", "l" + "c" * len(grids) + "c",
        "Variant & " + " & ".join(f"$N={n}$" for n in grids) + " & Rate \\\\")


def _refine_one(variant, t_end, n_grid):
    dx = 1.0 / n_grid
    grid = variant.grid_cls(shape=(n_grid, n_grid), dx=dx,
                            basis=R.get_basis(variant.basis), periodic=True)
    mat = NeoHookeanCompressible.from_E_nu(R.E, R.NU)
    p = ParticleSet.from_sampler(
        lambda q: np.ones(len(q), dtype=bool), ((0.0, 0.0), (1.0, 1.0)),
        dx, ppc=R.PPC, density=R.RHO)
    p.v[:] = R.shear_wave(p.x)
    c = mat.wave_speed_factor / np.sqrt(R.RHO)
    dt = 0.25 * dx / c
    s = ExplicitMPMStepper(grid, mat, variant.transfer, dt=dt)
    try:
        with quiet():
            s.run(p, n_steps=int(round(t_end / dt)))
        if not np.all(np.isfinite(p.F)):
            return None
        extra = {"domain": p.domain} if isinstance(grid, CPDIGrid) else {}
        st = grid.build_stencil(p.x, lp=getattr(p, "lp", None), **extra)
        return R.nodal_material_force_norm(p, grid, st, mat)
    except Exception:                                       # noqa: BLE001
        return None


def table_ranking(steps):
    names = list(R.BENCHMARKS)
    orders = {}
    for name, flow in R.BENCHMARKS.items():
        got = [(v.label, R.run_one_with_G(v, flow, steps)[1])
               for v in R.variants()]
        got = [g for g in got if g[1] is not None]
        orders[name] = [g[0] for g in sorted(got, key=lambda t: t[1])]

    rows, within, between = [], [], []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            r = R.spearman(orders[a], orders[b])
            same = R.DEFORMATION_CLASS[a] == R.DEFORMATION_CLASS[b]
            (within if same else between).append(r)
            rows.append(f"{a} & {b} & {'same' if same else 'different'} "
                        f"& {r:+.2f} \\\\")
    rows.append("\\midrule")
    rows.append(f"\\multicolumn{{3}}{{l}}{{mean, same class}} & "
                f"{np.mean(within):+.2f} \\\\")
    rows.append(f"\\multicolumn{{3}}{{l}}{{mean, different class}} & "
                f"{np.mean(between):+.2f} \\\\")
    return _table(
        "\n".join(rows),
        "Stability of the $\\|\\boldsymbol{\\mathcal{G}}_{i}\\|$ ordering across "
        "benchmarks, by deformation class. The ordering transfers within a "
        "class and much less between them.",
        "tab:ranking", "llcc",
        "Benchmark A & Benchmark B & Class & $\\rho$ \\\\")


