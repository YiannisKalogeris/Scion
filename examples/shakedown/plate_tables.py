#!/usr/bin/env python3
r"""
Table 4 of Example 2, written straight into the paper.

    python -m examples.shakedown.plate_tables --out _incoming
    python -m examples.shakedown.plate_tables --out _incoming --quick

Emits ``tab_plate.tex`` carrying its own caption, label and a provenance
comment, so ``main.tex`` only has to ``\input`` it and the table cannot drift
from the run that produced it. ``--quick`` says so in the caption; do not
paste a quick table into the manuscript.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

RESULTS = Path(__file__).parent / "results"


def _load(quick: bool):
    path = RESULTS / ("plate_quick.npz" if quick else "plate.npz")
    if not path.exists():
        raise SystemExit(f"{path} is missing; run probabilistic_plate first.")
    with np.load(path, allow_pickle=False) as data:
        return {k: data[k] for k in data.files}, path


def _tags(archive):
    return sorted((k[:-len("_modes")] for k in archive if k.endswith("_modes")),
                  key=lambda t: float(t[2:]))


def _counts(archive, tag):
    return sorted({int(k[len(tag) + 2:-3]) for k in archive
                   if k.startswith(f"{tag}_n") and k.endswith("_sd")})


def _weighted_moments(values, weights):
    mean = float(weights @ values)
    var = float(weights @ (values - mean) ** 2)
    return mean, np.sqrt(max(var, 0.0)) / mean


def table(archive, path, quick: bool) -> str:
    tags = _tags(archive)
    rows = []
    for tag in tags:
        ell = float(tag[2:])
        lam = archive[f"{tag}_lam"]
        ref_sd = archive[f"{tag}_ref_sd"]
        ref_mean, ref_cov = ref_sd.mean(), ref_sd.std() / ref_sd.mean()
        mc = {k: archive[f"{tag}_mc_{k}"] for k in ("E", "S")}
        # two design levels: the load factors at which the reference says 10%
        # and 1% of realizations have stopped shaking down
        not_sd = 1.0 - mc["E"] - mc["S"]
        design = [float(np.interp(q, not_sd, lam)) for q in (0.01, 0.10)]
        for n in _counts(archive, tag):
            sd = archive[f"{tag}_n{n}_sd"]
            w = archive[f"{tag}_n{n}_weights"]
            mean, cov = _weighted_moments(sd, w)
            gap = max(np.abs(archive[f"{tag}_n{n}_{k}"] - mc[k]).max()
                      for k in ("E", "S"))
            at_design = [
                abs(float(np.interp(d, lam,
                                    1.0 - archive[f"{tag}_n{n}_E"]
                                    - archive[f"{tag}_n{n}_S"]))
                    - float(np.interp(d, lam, not_sd))) for d in design]
            rows.append((ell, n, archive[f"{tag}_n{n}_el"].size,
                         mean / ref_mean - 1.0, cov, gap, at_design[0],
                         at_design[1],
                         float(archive[f"{tag}_n{n}_seconds"]),
                         float(archive[f"{tag}_ref_seconds"]),
                         ref_sd.size, ref_mean, ref_cov,
                         float(archive[f"{tag}_n{n}_band_residual"])))

    lines = [
        "% generated by examples/shakedown/plate_tables.py",
        f"% from {path.name}"
        + ("  -- QUICK RUN, NOT PUBLISHABLE" if quick else ""),
        r"\begin{table}[ht]",
        r"  \centering",
        r"  \caption{Example 2, direct probability integration against a "
        r"Monte Carlo reference through the same finite element model. "
        r"$\varepsilon_\mu$ is the relative error in the mean of "
        r"$\lambda_{\sd}$; the gap columns are the largest vertical "
        r"difference from the reference, overall and at the two load factors "
        r"at which the reference puts $1\%$ and $10\%$ of realizations past "
        r"shakedown."
        + (" \\textbf{Quick run: not publishable.}" if quick else "")
        + "}",
        r"  \label{tab:plate}",
        r"  \begin{tabular}{rrrrrrrr}",
        r"    \toprule",
        r"    $\ell_c/L$ & $N$ & $\varepsilon_\mu$ & CoV & worst gap "
        r"& at $1\%$ & at $10\%$ & seconds \\",
        r"    \midrule",
    ]
    last = None
    for (ell, n, _, emu, cov, gap, d1, d10, secs, ref_secs, ref_n,
         ref_mean, ref_cov, resid) in rows:
        if last is not None and ell != last:
            lines.append(r"    \midrule")
        last = ell
        lines.append(
            f"    {ell:g} & {n} & {emu:+.4f} & {cov:.4f} & {gap:.4f} "
            f"& {d1:.4f} & {d10:.4f} & {secs:.0f} \\\\")
    lines.append(r"    \midrule")
    for tag in tags:
        ell = float(tag[2:])
        ref_sd = archive[f"{tag}_ref_sd"]
        lines.append(
            f"    {ell:g} & {ref_sd.size}$^\\dagger$ & --- "
            f"& {ref_sd.std() / ref_sd.mean():.4f} & --- & --- & --- "
            f"& {float(archive[f'{tag}_ref_seconds']):.0f} \\\\")
    lines += [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \\[2pt]",
        r"  \footnotesize $^\dagger$ the Monte Carlo reference, whose own "
        r"standard error at a probability of one half is "
        + f"${1.0 / (2.0 * np.sqrt(archive[f'{tags[0]}_ref_sd'].size)):.3f}$"
        + r", so a gap below that is not resolved by the reference.",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("_incoming"))
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    archive, path = _load(args.quick)
    args.out.mkdir(parents=True, exist_ok=True)
    target = args.out / "tab_plate.tex"
    target.write_text(table(archive, path, args.quick))
    print(f"  {target}")

    # the numbers the prose quotes, printed so they are never transcribed by
    # hand from a figure
    print("\n  band residual, every correlation length and point count:")
    for tag in _tags(archive):
        for n in _counts(archive, tag):
            print(f"    l_c/L {float(tag[2:]):g}  N {n:5d}  "
                  f"{float(archive[f'{tag}_n{n}_band_residual']):.1e}")
    if "activity" in archive:
        prob = archive["activity"]
        w = archive["weights"]
        print(f"\n  activity map at lambda = "
              f"{float(archive['activity_lambda']):.4f}: "
              f"{int(archive['activity_counted'])} periodic, "
              f"{int(archive['activity_nonperiodic'])} not")
        print(f"    area fraction ever active   "
              f"{float(w[prob > 0].sum() / w.sum()):.4f}")
        print(f"    area fraction active in >50% of realizations "
              f"{float(w[prob > 0.5].sum() / w.sum()):.4f}")
        print(f"    peak probability            {prob.max():.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
