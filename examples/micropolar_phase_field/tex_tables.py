"""Emit the paper's sweep-table rows as LaTeX, straight from the saved runs.

    python -m examples.micropolar_phase_field.tex_tables

Generated rather than transcribed, for the reason recorded elsewhere in this
repository: a table typed by hand can drift from the run that produced it, and
nothing downstream would notice. Every number here is read from the ``.npz``
that the corresponding example wrote, so the table cannot disagree with the
calculation.

Reads whichever files are present:

    results/tension_data.npz        the completed sweep (peak loads, figures)
    results/tension_data_peak.npz   a --to-peak run (peak loads and shares)
    results/beam_data.npz           the beam sweep

A ``--to-peak`` run is preferred for the *shares* when both are present, since
a full run made before the shares were persisted does not carry them; the peak
loads agree between the two by construction.
"""
from __future__ import annotations

import pathlib

import numpy as np

# Deliberately not ``from ._common import RESULTS``: this script only reads
# files that the examples already wrote and needs no part of the library, so it
# should run as a plain script as well as a module.
RESULTS = pathlib.Path(__file__).resolve().parent / "results"

SHARE_COLS = ("symmetric", "relative_rotation", "curvature")


def _peak(load):
    return int(np.argmax(np.abs(load)))


def _fmt(x, sig=3):
    """Shares span a few decades, so a fixed format is wrong for some of them."""
    if x == 0.0:
        return "$0$"
    if abs(x) < 1e-1:
        m, e = f"{x:.{sig - 1}e}".split("e")
        return rf"${m}\times10^{{{int(e)}}}$"
    return f"${x:.{sig}g}$"


def tension():
    full = RESULTS / "tension_data.npz"
    peak = RESULTS / "tension_data_peak.npz"
    src = peak if peak.exists() else full
    if not src.exists():
        print("  (no tension data yet)")
        return
    d = np.load(src, allow_pickle=True)
    has_shares = any(k.endswith("_shares") for k in d.files)
    print(f"%% generated by tex_tables.py from {src.name}")
    if not has_shares:
        print("%% WARNING: this run carries no shares; re-run with --to-peak")
    order = [("classical", "classical", None), ("lb0", "$0$", "--"),
             ("lb1", "$1$", "$4$"), ("lb2", "$2$", "$8$"),
             ("lb4", "$4$", "$16$")]
    base = None
    for tag, lab, cells in order:
        if f"{tag}_load" not in d.files:
            continue
        load = d[f"{tag}_load"]
        pk = abs(load[_peak(load)])
        base = pk if base is None else base
        if tag == "classical":
            print(rf"classical & -- & ${pk:.5f}$ & $1.0000$ & -- & -- \\")
            continue
        if has_shares and f"{tag}_shares" in d.files:
            sh = d[f"{tag}_shares"][_peak(load)]
            rel, curv = _fmt(float(sh[1])), _fmt(float(sh[2]))
        else:
            rel = curv = r"\TODO"
        print(rf"{lab} & {cells} & ${pk:.5f}$ & ${pk / base:.4f}$ "
              rf"& {rel} & {curv} \\")


def beam():
    src = RESULTS / "beam_data.npz"
    if not src.exists():
        print("  (no beam data yet)")
        return
    d = np.load(src, allow_pickle=True)
    print(f"%% generated by tex_tables.py from {src.name}")
    ratios = d["l_b_over_h"]
    base = None
    for i, r in enumerate(ratios):
        load = d[f"row{i}_load"]
        pk = abs(load[_peak(load)])
        base = pk if base is None else base
        sh = d[f"row{i}_shares"][_peak(load)]
        cells = "--" if r == 0 else f"${r * 0.4 / 0.01:.0f}$"
        print(rf"${r:.3g}$ & {cells} & ${pk:#.4g}$ & ${pk / base:.4f}$ "
              rf"& {_fmt(float(sh[1]))} & {_fmt(float(sh[2]))} \\")


if __name__ == "__main__":
    print("\n%% ---- Table: single-edge notched tension ----")
    tension()
    print("\n%% ---- Table: notched beam ----")
    beam()
