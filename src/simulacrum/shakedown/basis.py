r"""
A reduced basis of self-equilibrated residual stress fields.

This module exists because the obvious thing does not work.

Melan's theorem allows *any* self-equilibrated residual field, and in a
displacement-based finite element model that set is enormous: independent stress
components at every quadrature point, constrained only by weak equilibrium
against the displacement test space. On a 24x24 mesh of the thick cylinder that
is about 8000 free parameters against 2300 yield constraints. Optimising freely
over it does not give a conservative answer -- it gives a meaningless one. The
measured factors ran from 1.4 to 3 x 10^5 times the analytic limit load, without
converging under refinement, because the optimiser finds deviatoric fields whose
divergence no pressure field could balance pointwise and which only weak
equilibrium fails to exclude.

The standard remedy in the shakedown literature is to search a *reduced* space:
express the residual field as a linear combination of a small number of basis
fields, each of which is a genuine self-equilibrated stress field generated by
an actual elastic computation. Simon and Weichert, Zhang and Liu and others
build them as "elastic responses of the body to imposed permanent strains
obtained through elastic-plastic incremental analysis", or equivalently as
differences of intermediate stresses during equilibrium iteration -- both being
in equilibrium with the same external load, their difference is residual by
construction.

Tens of coefficients instead of thousands of components turns the problem from
under- to over-determined, and the answer becomes an engineering number again.

How a basis field is built
--------------------------
An imposed eigenstrain ``eps*`` -- a permanent strain the material would like to
have -- generates a residual field once the structure is allowed to relax:

    rho = C : (eps(v) - eps*),    K v = A (C eps*)

The displacement ``v`` is whatever the structure needs to restore equilibrium,
and the result satisfies ``A rho = K v - A(C eps*) = 0`` exactly, to the accuracy
of the linear solve. Nothing about it is approximate: every basis field is
self-equilibrated by construction, so every combination of them is too, and the
equality constraint disappears from the optimisation entirely.

Where the eigenstrains come from
--------------------------------
:meth:`ResidualBasis.from_overstress` uses the plastic strain a radial return
would produce if the elastic solution were applied at a load level above first
yield:

    eps* = <q - sigma_y>_+ * s / (2 G q)

evaluated at each vertex of the load domain and at a spread of load levels. That
is the cheap stand-in for a full incremental analysis: it puts permanent strain
exactly where the structure would actually yield, in the direction it would
actually flow, and one level gives one mode. Sweeping the level plays the role
of the load steps in an incremental run.

What this is and is not
-----------------------
Restricting the basis can only *lower* the computed factor, so it is safe in the
direction that matters. What it does not do is make the underlying discrete
problem rigorous: yield is still checked at quadrature points and equilibrium is
still weak, so the result is a lower bound of the discrete model rather than a
strict bound on the continuum. A strict bound needs a statically admissible
stress discretisation -- element-wise linear stresses with enforced traction
continuity, in the manner of Sloan's lower-bound limit analysis -- which is a
different element family, not a different search space.
"""

from __future__ import annotations

import numpy as np
from scipy.sparse import linalg as spla

from ..materials.notation import from_mandel, mandel_to_voigt_tangent, to_mandel
from ..materials.notation import voigt_strain_to_mandel

__all__ = ["ResidualBasis"]


class ResidualBasis:
    """Orthonormal self-equilibrated fields spanning the search space.

    Parameters
    ----------
    tables : the quadrature tables of the mesh.
    C_mandel : ``(6, 6)`` elastic stiffness in Mandel form.
    equilibrium : a :class:`~simulacrum.shakedown.equilibrium.SelfEquilibrium`,
        used for its internal-force operator and to verify the modes.
    scale : the stress the modes are normalised to, normally the yield stress.
        It makes the coefficients dimensionless and of order one, which is what
        lets a quasi-Newton method work on them without preconditioning.
    """

    def __init__(self, tables, C_mandel, equilibrium, scale: float = 1.0):
        self.tables = tables
        self.equilibrium = equilibrium
        self.C = np.asarray(C_mandel, dtype=float)
        self.dim = tables.dim
        self.n_points = tables.n_points
        self.scale = float(scale)
        # Mandel carries 2*mu on the shear diagonal, so the shear modulus comes
        # straight off the stiffness rather than being passed in again and
        # risking disagreement with it
        self.shear_modulus = 0.5 * float(self.C[3, 3])

        w = tables.w.ravel()
        self._w = w
        self._volume = float(w.sum())

        nv = tables.n_voigt
        C_v = mandel_to_voigt_tangent(self.C[None], self.dim)[0]
        K, _ = tables.stiffness_and_force(
            np.zeros((self.n_points, nv)),
            np.broadcast_to(C_v, (self.n_points, nv, nv)),
            equilibrium.n_dof)
        self._K = K.tocsr()
        self._solve = spla.factorized(
            self._K[equilibrium.free][:, equilibrium.free].tocsc())

        self.modes: list[np.ndarray] = []
        self.sources: list[str] = []

    # ------------------------------------------------------------------
    @property
    def n_modes(self) -> int:
        return len(self.modes)

    def inner(self, a: np.ndarray, b: np.ndarray) -> float:
        """``<a, b>_w / V``: the quadrature-weighted mean of ``a : b``."""
        return float((self._w * np.einsum("pi,pi->p", a, b)).sum()
                     / self._volume)

    def norm(self, a: np.ndarray) -> float:
        return float(np.sqrt(max(self.inner(a, a), 0.0)))

    # ------------------------------------------------------------------
    def relax(self, eigenstrain: np.ndarray) -> np.ndarray:
        """The residual field left by an imposed eigenstrain, ``(n_points, 6)``.

        ``rho = C : (eps(v) - eps*)`` with ``K v = A(C eps*)``. Self-equilibrated
        by construction: whatever the eigenstrain, the structure relaxes until
        the internal force of the result vanishes.
        """
        eps_star = np.asarray(eigenstrain, dtype=float).reshape(
            self.n_points, 6)
        sigma_star = eps_star @ self.C.T
        f = self.equilibrium.internal_force(sigma_star)

        v = np.zeros(self.equilibrium.n_dof)
        free = self.equilibrium.free
        v[free] = self._solve(f[free])
        eps_v = voigt_strain_to_mandel(self.tables.strains_voigt(v), self.dim)
        return eps_v @ self.C.T - sigma_star

    # ------------------------------------------------------------------
    def add(self, field: np.ndarray, source: str = "",
            tol: float = 1.0e-10) -> bool:
        """Orthonormalise a candidate against the basis and keep it if new.

        Modified Gram-Schmidt in the weighted inner product, twice -- one pass
        loses orthogonality badly once the modes are nearly parallel, which they
        are here, because eigenstrain modes from neighbouring load levels differ
        only slightly. Returns whether the field survived.

        A candidate that collapses to nothing is not an error. It means the
        generator produced a direction the basis already has, and the honest
        response is to drop it rather than to carry a near-null vector that
        makes the optimisation ill-conditioned.
        """
        v = np.array(field, dtype=float, copy=True).reshape(self.n_points, 6)
        start = self.norm(v)
        if start <= 0.0:
            return False

        # Project before anything else. A field arriving from outside -- the
        # converged mechanism of a linear matching run, say -- need not be
        # admissible for *this* equilibrium operator, and a basis mode that is
        # not self-equilibrated destroys the one property the whole method
        # rests on. The commonest way for it to happen is a B-bar mesh: B-bar
        # modifies the equilibrium operator, so a field self-equilibrated
        # against B_bar is not against B, and the resulting "lower bound" comes
        # out above the true answer while every other check still passes.
        v = self.equilibrium.project(v)
        if not np.all(np.isfinite(v)):
            return False

        # Measure independence against what survived the projection, not
        # against what came in. A candidate that is mostly inadmissible leaves
        # a small remainder, and comparing that with the original norm would
        # divide by a nearly-null vector and put an infinity in the basis.
        start = self.norm(v)
        if start <= 0.0:
            return False

        for _ in range(2):
            for m in self.modes:
                v -= (self.inner(v, m) / self.scale ** 2) * m

        remaining = self.norm(v)
        if not np.isfinite(remaining) or remaining <= tol * start:
            return False

        self.modes.append(v * (self.scale / remaining))
        self.sources.append(source)
        return True

    def add_eigenstrain(self, eigenstrain: np.ndarray, source: str = "") -> bool:
        """Relax an eigenstrain and add the residual field it leaves."""
        return self.add(self.relax(eigenstrain), source)

    # ------------------------------------------------------------------
    def from_overstress(self, vertex_stresses: np.ndarray, criterion, kappa,
                        levels=None, elastic_factor: float = 1.0
                        ) -> "ResidualBasis":
        """Generate modes from the plastic strain the elastic solution implies.

        For each load vertex and each level ``mu``, the eigenstrain is the
        plastic strain a radial return would leave if ``mu * sigma^E`` were
        applied to a perfectly plastic material:

            eps* = <f(mu sigma^E)>_+ / (2 G) * df/dsigma

        Zero wherever the elastic solution is admissible, so the permanent
        strain is placed exactly where the structure yields and points the way
        it would flow. One level is one mode; the sweep over levels does what
        the load steps of an incremental analysis would do.

        ``levels`` are multiples of ``elastic_factor``; the default sweeps from
        just past first yield to three times it. Modes that add nothing to the
        span are dropped silently -- see :meth:`add`.
        """
        vertex_stresses = np.asarray(vertex_stresses, dtype=float)
        if levels is None:
            levels = np.linspace(1.05, 3.0, 8)
        kappa_arr = np.broadcast_to(np.asarray(kappa, dtype=float),
                                    (self.n_points,))

        for k, shat in enumerate(vertex_stresses):
            for mu in np.atleast_1d(np.asarray(levels, dtype=float)):
                lam = float(mu) * float(elastic_factor)
                tensor = from_mandel(lam * shat)
                excess = np.maximum(criterion.f(tensor, kappa_arr), 0.0)
                if not excess.any():
                    continue
                eps_star = (excess / (2.0 * self.shear_modulus))[:, None] \
                    * to_mandel(criterion.df_dsigma(tensor))
                self.add_eigenstrain(eps_star, f"vertex {k}, mu = {mu:.3g}")
        return self

    def enrich(self, rho: np.ndarray, vertex_stresses: np.ndarray, lam: float,
               criterion, kappa) -> int:
        """Add modes aimed at the constraints that are currently violated.

        The reduced-basis solve is only as good as the directions it was given,
        so the literature runs it "in a sequence of reduced subspaces": solve,
        look at what is still violated, generate eigenstrains there, solve
        again. This is one round of that. Returns how many modes were kept.
        """
        kappa_arr = np.broadcast_to(np.asarray(kappa, dtype=float),
                                    (self.n_points,))
        kept = 0
        for k, shat in enumerate(np.asarray(vertex_stresses, dtype=float)):
            tensor = from_mandel(rho + lam * shat)
            excess = np.maximum(criterion.f(tensor, kappa_arr), 0.0)
            if not excess.any():
                continue
            eps_star = (excess / (2.0 * self.shear_modulus))[:, None] \
                * to_mandel(criterion.df_dsigma(tensor))
            kept += bool(self.add_eigenstrain(
                eps_star, f"enrichment at lambda = {lam:.4g}, vertex {k}"))
        return kept

    # ------------------------------------------------------------------
    def field(self, coefficients) -> np.ndarray:
        """``sum beta_j rho_j``, ``(n_points, 6)``. Self-equilibrated for any
        coefficients, which is why the optimisation is unconstrained."""
        beta = np.asarray(coefficients, dtype=float)
        if beta.size != self.n_modes:
            raise ValueError(f"got {beta.size} coefficients for "
                             f"{self.n_modes} modes")
        if not self.n_modes:
            return np.zeros((self.n_points, 6))
        return np.einsum("j,jpi->pi", beta, np.stack(self.modes))

    def project_gradient(self, grad_rho: np.ndarray) -> np.ndarray:
        """Chain rule onto the coefficients: ``dPhi/dbeta_j = <dPhi/drho, rho_j>``.

        A plain contraction, not a weighted one -- ``grad_rho`` is the Euclidean
        gradient with respect to the field and already carries whatever weights
        the objective put there.
        """
        if not self.n_modes:
            return np.zeros(0)
        return np.einsum("pi,jpi->j", grad_rho, np.stack(self.modes))

    # ------------------------------------------------------------------
    def verify(self) -> dict:
        """Check that the modes are what they claim to be.

        Every mode must be self-equilibrated -- that is the entire reason the
        optimisation can ignore the equilibrium constraint -- and the set must
        be orthonormal, or the coefficients are badly scaled and the optimiser
        stalls for reasons that look like a bad objective.
        """
        if not self.n_modes:
            return {"n_modes": 0, "max_equilibrium_residual": 0.0,
                    "max_gram_error": 0.0, "ok": True}

        worst_eq = max(self.equilibrium.residual(m) for m in self.modes)
        stack = np.stack(self.modes)
        gram = np.einsum("p,ipj,kpj->ik", self._w, stack, stack) \
            / (self._volume * self.scale ** 2)
        gram_error = float(np.abs(gram - np.eye(self.n_modes)).max())
        return {
            "n_modes": self.n_modes,
            "max_equilibrium_residual": float(worst_eq),
            "max_gram_error": gram_error,
            "ok": bool(worst_eq < 1e-8 and gram_error < 1e-8),
        }

    def __len__(self) -> int:
        return self.n_modes

    def __repr__(self) -> str:
        return (f"ResidualBasis({self.n_modes} modes, "
                f"{self.n_points} points, scale={self.scale:g})")
