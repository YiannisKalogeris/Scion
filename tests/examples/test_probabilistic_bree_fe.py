"""
Verification for Example 1b, the probabilistic Bree problem on a finite
element model.

The mechanics is a tabulated map rather than a closed form, so the checks here
are the ones that do not depend on the map's values: that the reduction to a
ray direction is exact, that the band identity still holds structurally, and
that the ray with no alternating regime still reports none.

python -m pytest tests/examples/test_probabilistic_bree_fe.py -q
"""

from __future__ import annotations

import numpy as np
import pytest

from scion.shakedown import transition_loads
from scion.uq.density import gf_points

from examples.shakedown.probabilistic_bree import (RAYS, distribution,
                                                   monte_carlo, ray_means,
                                                   regime_curves)
from examples.shakedown.probabilistic_bree_fe import MAP, FEMap

pytestmark = pytest.mark.skipif(
    not MAP.exists(),
    reason="the finite element map is generated by examples/shakedown/"
           "fe_bree_map.py and is not checked in")


def test_the_map_is_homogeneous_of_degree_minus_one_in_the_load():
    """The reduction to a ray direction, which is the whole reason the map is
    a function of one angle. Exact rather than approximate, so asserted to
    round-off."""
    fe = FEMap()
    base = fe(np.array([0.1]), np.array([0.8]))
    for c in (0.5, 1.7, 3.0):
        scaled = fe(np.array([0.1 * c]), np.array([0.8 * c]))
        for name in ("elastic", "shakedown", "ratchet"):
            assert (getattr(scaled, name).item() * c
                    == pytest.approx(getattr(base, name).item(), rel=1e-12))


def test_the_transition_loads_are_ordered():
    """``lambda_el <= lambda_sd <= lambda_rr`` at every tabulated direction.

    Not a tautology: the three come from three different calculations -- an
    elastic evaluation, a first-passage bisection on the regime, and a
    bisection on the ratchet rate -- so an ordering violation would mean one
    of them is wrong."""
    d = np.load(MAP)
    assert np.all(d["fe_el"] <= d["fe_sd"] + 1e-12)
    assert np.all(d["fe_sd"] <= d["fe_rr"] + 1e-12)


def test_the_four_regime_probabilities_still_sum_to_exactly_one():
    """Structural, and independent of the mechanics: the bands are differences
    of cumulative distribution functions of the same transition loads, closed
    on one side only."""
    fe = FEMap()
    dT, sP = ray_means(*RAYS["A"])
    points = gf_points(distribution(dT, sP), 128)
    lam = np.linspace(0.3, 6.0, 25)
    curves, _ = regime_curves(points, lam, loads_of=fe)
    assert np.abs(sum(curves.values()) - 1.0).max() == 0.0


def test_ray_B_carries_no_alternating_plasticity_on_the_FE_map_either():
    """The structural check that no error norm on ray A could reveal.

    Ray B leaves shakedown across ``y = 4(1-x)``, where the alternating band
    is empty, and the finite element model inherits that: measured, the state
    goes from shakedown straight to one-way ratcheting with ``r`` and
    ``Delta eps^p`` identically equal."""
    fe = FEMap()
    dT, sP = ray_means(*RAYS["B"])
    dist = distribution(dT, sP)
    lam = np.linspace(0.3, 4.0, 30)
    curves, _ = regime_curves(gf_points(dist, 256), lam, loads_of=fe)
    assert curves["AP"].max() == 0.0
    ref, _, _ = monte_carlo(dist, 20_000, lam, loads_of=fe)
    assert ref["AP"].max() == 0.0


def test_the_FE_map_sits_above_the_closed_form_on_both_rays():
    """Plane strain is stiffer against yield than Bree's uniaxial
    idealization, so every transition load moves up; the offsets are one
    constant per branch and are quoted in the manuscript. Asserted only as a
    direction and a bound, since the constants are measurements."""
    fe = FEMap()
    for x_hat, y_hat in RAYS.values():
        got = fe(np.array([x_hat]), np.array([y_hat]))
        want = transition_loads(x_hat, y_hat)
        for name in ("elastic", "shakedown"):
            ratio = (getattr(got, name).item()
                     / float(np.ravel(getattr(want, name))[0]))
            assert 1.0 < ratio < 1.25, (name, x_hat, y_hat, ratio)


def test_no_realization_falls_outside_the_tabulated_directions():
    """A clamped realization is one the map does not cover, so the count has
    to be zero for the comparison to mean anything."""
    fe = FEMap()
    for x_hat, y_hat in RAYS.values():
        dT, sP = ray_means(x_hat, y_hat)
        monte_carlo(distribution(dT, sP), 50_000, np.array([1.0]), loads_of=fe)
    assert fe.clamped == 0
